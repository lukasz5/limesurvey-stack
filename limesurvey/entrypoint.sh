#!/bin/sh
# Prepares runtime config, waits for the database, installs LimeSurvey on
# first start or migrates the schema on upgrades, then starts Apache.
set -eu

log() { printf '[limesurvey] %s\n' "$*"; }
die() { printf '[limesurvey] ERROR: %s\n' "$*" >&2; exit 1; }

read_secret() {
  # $1 = variable name; reads $1 or the file named by ${1}_FILE.
  eval "val=\${$1:-}"
  eval "file=\${$1_FILE:-}"
  if [ -n "$file" ]; then
    [ -r "$file" ] || die "$1_FILE ($file) is not readable by $(id -un)"
    val=$(cat "$file")
  fi
  printf '%s' "$val"
}

: "${DB_HOST:=db}"
: "${DB_PORT:=3306}"
: "${DB_NAME:=limesurvey}"
: "${DB_USER:=limesurvey}"
: "${DB_TABLE_PREFIX:=lime_}"
: "${LS_DEBUG:=0}"
: "${ADMIN_USER:=admin}"
: "${ADMIN_NAME:=Administrator}"
: "${ADMIN_EMAIL:=}"

DB_PASSWORD=$(read_secret DB_PASSWORD)
[ -n "$DB_PASSWORD" ] || die 'DB_PASSWORD or DB_PASSWORD_FILE is required.'

STATE=/var/lib/limesurvey
umask 077

# ---- Writable scratch dirs (tmp/ is a tmpfs) ----
mkdir -p tmp/assets tmp/runtime tmp/upload upload/surveys upload/themes/survey \
         upload/themes/question upload/fonts upload/twig/extensions

# ---- config.php (regenerated on every start from env + secrets) ----
export DB_HOST DB_PORT DB_NAME DB_USER DB_PASSWORD DB_TABLE_PREFIX LS_DEBUG
php -d display_errors=stderr -r '
$dsn = sprintf("mysql:host=%s;port=%d;dbname=%s;",
    getenv("DB_HOST"), (int) getenv("DB_PORT"), getenv("DB_NAME"));
$cfg = [
  "components" => [
    "db" => [
      "connectionString" => $dsn,
      "emulatePrepare"   => true,
      "username"         => getenv("DB_USER"),
      "password"         => getenv("DB_PASSWORD"),
      "charset"          => "utf8mb4",
      "tablePrefix"      => getenv("DB_TABLE_PREFIX"),
    ],
    "session" => [
      "class"            => "application.core.web.DbHttpSession",
      "connectionID"     => "db",
      "sessionTableName" => "{{sessions}}",
    ],
    "urlManager" => [
      "urlFormat"      => "path",
      "rules"          => [],
      "showScriptName" => true,
    ],
  ],
  "config" => [
    "debug"    => (int) getenv("LS_DEBUG"),
    "debugsql" => 0,
  ],
];
$php = "<?php if (!defined(\"BASEPATH\")) exit(\"No direct script access allowed\");\n"
     . "// Generated by the container entrypoint on every start. Do not edit.\n"
     . "return " . var_export($cfg, true) . ";\n";
file_put_contents("/var/lib/limesurvey/config.php.new", $php) !== false || exit(1);
rename("/var/lib/limesurvey/config.php.new", "/var/lib/limesurvey/config.php") || exit(1);
' || die 'Could not write config.php'
unset DB_PASSWORD

# ---- security.php (data-encryption keys, created once, NEVER rotated) ----
if [ ! -s "$STATE/security.php" ]; then
  log 'Generating data-encryption keys (security.php).'
  php -r '
$nonce = sodium_bin2hex(random_bytes(SODIUM_CRYPTO_SECRETBOX_NONCEBYTES));
$key   = sodium_bin2hex(sodium_crypto_secretbox_keygen());
$php = "<?php if (!defined(\"BASEPATH\")) exit(\"No direct script access allowed\");\n"
     . "// Data-encryption keys. Back this file up. Changing it makes encrypted responses unreadable.\n"
     . "\$config = array();\n"
     . "\$config[\"encryptionnonce\"] = \"$nonce\";\n"
     . "\$config[\"encryptionsecretboxkey\"] = \"$key\";\n"
     . "return \$config;\n";
file_put_contents("/var/lib/limesurvey/security.php", $php) !== false || exit(1);
' || die 'Could not write security.php'
fi

# ---- Wait for the database ----
log "Waiting for database at $DB_HOST:$DB_PORT ..."
php -r '
define("BASEPATH", 1);
$db = (require "/var/lib/limesurvey/config.php")["components"]["db"];
for ($i = 0; $i < 90; $i++) {
    try {
        new PDO($db["connectionString"], $db["username"], $db["password"], [PDO::ATTR_TIMEOUT => 2]);
        exit(0);
    } catch (Throwable $e) { sleep(2); }
}
fwrite(STDERR, $e->getMessage() . "\n");
exit(1);
' || die 'Database did not become available.'

# ---- Install or upgrade ----
installed=$(php -r '
define("BASEPATH", 1);
$db = (require "/var/lib/limesurvey/config.php")["components"]["db"];
$pdo = new PDO($db["connectionString"], $db["username"], $db["password"]);
$st = $pdo->prepare("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = ?");
$st->execute([$db["tablePrefix"] . "settings_global"]);
echo $st->fetchColumn() ? "yes" : "no";
')

if [ "$installed" = no ]; then
  ADMIN_PASSWORD=$(read_secret ADMIN_PASSWORD)
  [ -n "$ADMIN_PASSWORD" ] || die 'First start: ADMIN_PASSWORD or ADMIN_PASSWORD_FILE is required.'
  [ -n "$ADMIN_EMAIL" ] || die 'First start: ADMIN_EMAIL is required.'
  log "Empty database: installing LimeSurvey (admin user: $ADMIN_USER)."
  php application/commands/console.php install \
    "$ADMIN_USER" "$ADMIN_PASSWORD" "$ADMIN_NAME" "$ADMIN_EMAIL" \
    || die 'Installation failed.'
  unset ADMIN_PASSWORD
else
  log 'Existing installation: applying database migrations if any.'
  php application/commands/console.php updatedb || die 'Database update failed.'
fi

log 'Starting web server.'
exec "$@"
